static TILE MapGetTile(int x, int y){
    if ((y < 0 || y >= MAP_HEIGHT) || (x < 0 || x >= MAP_WIDTH)){
        return TILE_WALL;
    }
    return map[y][x];
}

bool MapTileIsWall(int x, int y){
    return MapGetTile(x, y) == TILE_WALL;
}